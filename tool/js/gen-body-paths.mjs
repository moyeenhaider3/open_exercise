import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import esbuild from 'esbuild';
import { MUSCLES, INERT } from '../../third_party/opengym/lib/muscles.js';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const projectRoot = path.resolve(__dirname, '../..');
const bodyPathsJsPath = path.resolve(projectRoot, '../openGym/frontend/src/lib/body-paths.js');
const assetsBodyDir = path.resolve(projectRoot, 'assets/body');

if (!fs.existsSync(bodyPathsJsPath)) {
  console.error(`Error: body-paths.js not found at ${bodyPathsJsPath}`);
  process.exit(1);
}

fs.mkdirSync(assetsBodyDir, { recursive: true });

const sourceCode = fs.readFileSync(bodyPathsJsPath, 'utf8');
const sourceSha256 = crypto.createHash('sha256').update(sourceCode).digest('hex');

const transformed = esbuild.transformSync(sourceCode, { format: 'cjs' });
const mod = { exports: {} };
const fn = new Function('module', 'exports', transformed.code);
fn(mod, mod.exports);

const bodyPaths = mod.exports.default || mod.exports;

function escapeXmlAttr(str) {
  return str
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;');
}

const bodies = ['male', 'female'];
const views = ['front', 'back'];

for (const body of bodies) {
  for (const viewName of views) {
    const viewData = bodyPaths[body]?.[viewName];
    if (!viewData) {
      console.error(`Error: Missing viewData for ${body} ${viewName}`);
      process.exit(1);
    }

    const { vb, p } = viewData;
    const pKeys = Object.keys(p);
    let totalExpectedPaths = 0;
    for (const k of pKeys) {
      if (!INERT.includes(k) && !MUSCLES.includes(k)) {
        console.error(`Error: Part "${k}" in ${body} ${viewName} is neither in INERT nor in MUSCLES!`);
        process.exit(1);
      }
      totalExpectedPaths += p[k].length;
    }

    const inertSet = new Set(INERT);
    const lines = [];
    lines.push('<?xml version="1.0" encoding="UTF-8"?>');
    lines.push('<!--');
    lines.push('  SPDX-License-Identifier: AGPL-3.0-or-later');
    lines.push('  GENERATED by tool/gen_body_paths.sh from ../openGym/frontend/src/lib/body-paths.js — do not edit');
    lines.push(`  Source SHA256: ${sourceSha256}`);
    lines.push('  Geometry: MuscleMap by Melih Colpan (MIT), see NOTICE.md');
    lines.push('-->');
    lines.push(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="${vb}" data-body="${body}" data-view="${viewName}">`);

    let inertPathCount = 0;
    let musclePathCount = 0;

    // Paint order: INERT parts in INERT order
    for (const slug of INERT) {
      const paths = p[slug];
      if (!paths || !Array.isArray(paths)) continue;
      for (const d of paths) {
        lines.push(`  <path data-part="${slug}" data-kind="inert" d="${escapeXmlAttr(d)}"/>`);
        inertPathCount++;
      }
    }

    // Paint order: MUSCLES parts in MUSCLES order
    for (const slug of MUSCLES) {
      const paths = p[slug];
      if (!paths || !Array.isArray(paths)) continue;
      for (const d of paths) {
        lines.push(`  <path data-part="${slug}" data-kind="muscle" d="${escapeXmlAttr(d)}"/>`);
        musclePathCount++;
      }
    }

    lines.push('</svg>');
    lines.push('');

    const totalEmittedPaths = inertPathCount + musclePathCount;
    if (totalEmittedPaths !== totalExpectedPaths) {
      console.error(
        `Error: Emitted ${totalEmittedPaths} paths but expected ${totalExpectedPaths} for ${body} ${viewName}`
      );
      process.exit(1);
    }

    const outFileName = `${body}-${viewName}.svg`;
    const outFilePath = path.join(assetsBodyDir, outFileName);
    fs.writeFileSync(outFilePath, lines.join('\n'), 'utf8');

    console.log(
      `${outFileName} vb="${vb}" paths=${totalEmittedPaths} inert=${inertPathCount} muscle=${musclePathCount}`
    );
  }
}
