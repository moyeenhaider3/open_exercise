import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import esbuild from 'esbuild';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const projectRoot = path.resolve(__dirname, '../..');
const iconJsxPath = path.resolve(projectRoot, '../openGym/frontend/src/components/Icon.jsx');
const outputPath = path.resolve(projectRoot, 'lib/core/ui_kit/icons/app_icon_data.g.dart');

if (!fs.existsSync(iconJsxPath)) {
  console.error(`Error: Icon.jsx not found at ${iconJsxPath}`);
  process.exit(1);
}

const sourceCode = fs.readFileSync(iconJsxPath, 'utf8');
const sourceSha256 = crypto.createHash('sha256').update(sourceCode).digest('hex');

const transformed = esbuild.transformSync(sourceCode, {
  loader: 'jsx',
  jsxFactory: '__h',
  jsxFragment: '__Frag',
  format: 'cjs',
});

const __Frag = Symbol('Fragment');
function __h(type, props, ...children) {
  if (type === __Frag) {
    return children.flat(Infinity);
  }
  return [{ type, props: props || {} }];
}

const mod = { exports: {} };
const fn = new Function(
  '__h',
  '__Frag',
  'module',
  'exports',
  transformed.code + '\nmodule.exports.P = P;\n',
);
fn(__h, __Frag, mod, mod.exports);

const { P, ICON_NAMES } = mod.exports;

if (!P || !ICON_NAMES) {
  console.error('Error: Failed to extract P or ICON_NAMES from Icon.jsx');
  process.exit(1);
}

const lines = [];
lines.push('// SPDX-License-Identifier: AGPL-3.0-or-later');
lines.push('// GENERATED by tool/gen_icons.sh from ../openGym/frontend/src/components/Icon.jsx — do not edit');
lines.push(`// Source SHA256: ${sourceSha256}`);
lines.push('');
lines.push('/// Icon element data for openGym icon set.');
lines.push('library;');
lines.push('');
lines.push('enum IconElementType {');
lines.push('  path,');
lines.push('  rect,');
lines.push('  circle,');
lines.push('  ellipse,');
lines.push('  line,');
lines.push('  polyline,');
lines.push('  polygon,');
lines.push('}');
lines.push('');
lines.push('class IconElement {');
lines.push('  const IconElement({');
lines.push('    required this.type,');
lines.push('    this.d,');
lines.push('    this.x,');
lines.push('    this.y,');
lines.push('    this.width,');
lines.push('    this.height,');
lines.push('    this.rx,');
lines.push('    this.cx,');
lines.push('    this.cy,');
lines.push('    this.r,');
lines.push('    this.fill,');
lines.push('    this.stroke,');
lines.push('    this.opacity,');
lines.push('  });');
lines.push('');
lines.push('  final IconElementType type;');
lines.push('  final String? d;');
lines.push('  final double? x;');
lines.push('  final double? y;');
lines.push('  final double? width;');
lines.push('  final double? height;');
lines.push('  final double? rx;');
lines.push('  final double? cx;');
lines.push('  final double? cy;');
lines.push('  final double? r;');
lines.push('  final String? fill;');
lines.push('  final String? stroke;');
lines.push('  final double? opacity;');
lines.push('}');
lines.push('');
lines.push('/// List of all icon names in openGym ICON_NAMES order.');
lines.push('const List<String> kIconNames = <String>[');
for (const name of ICON_NAMES) {
  lines.push(`  '${name}',`);
}
lines.push('];');
lines.push('');
lines.push('/// Map of icon name to list of SVG elements.');
lines.push('const Map<String, List<IconElement>> kIconData = <String, List<IconElement>>{');

for (const name of Object.keys(P)) {
  const elements = P[name];
  lines.push(`  '${name}': <IconElement>[`);
  for (const el of elements) {
    const props = el.props || {};
    const parts = [`type: IconElementType.${el.type}`];
    if (props.d !== undefined) {
      parts.push(`d: '${props.d.replace(/'/g, "\\'")}'`);
    }
    if (props.x !== undefined) {
      parts.push(`x: ${Number(props.x)}`);
    }
    if (props.y !== undefined) {
      parts.push(`y: ${Number(props.y)}`);
    }
    if (props.width !== undefined) {
      parts.push(`width: ${Number(props.width)}`);
    }
    if (props.height !== undefined) {
      parts.push(`height: ${Number(props.height)}`);
    }
    if (props.rx !== undefined) {
      parts.push(`rx: ${Number(props.rx)}`);
    }
    if (props.cx !== undefined) {
      parts.push(`cx: ${Number(props.cx)}`);
    }
    if (props.cy !== undefined) {
      parts.push(`cy: ${Number(props.cy)}`);
    }
    if (props.r !== undefined) {
      parts.push(`r: ${Number(props.r)}`);
    }
    if (props.fill !== undefined) {
      parts.push(`fill: '${props.fill}'`);
    }
    if (props.stroke !== undefined) {
      parts.push(`stroke: '${props.stroke}'`);
    }
    if (props.opacity !== undefined) {
      parts.push(`opacity: ${Number(props.opacity)}`);
    }
    lines.push(`    IconElement(${parts.join(', ')}),`);
  }
  lines.push('  ],');
}

lines.push('};');
lines.push('');

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, lines.join('\n'), 'utf8');
console.log(`Generated ${outputPath} with ${ICON_NAMES.length} icons (source SHA: ${sourceSha256.substring(0, 12)}).`);
